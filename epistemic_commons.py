    # PUBLIC API
    # ══════════════════════════════════════════════════════════════════════════

    def get_ai_context_packet(self) -> str:
        """
        Returns today's AI context packet as a string.
        Use this to inject into any AI system's context window.

        Example:
            context = commons.get_ai_context_packet()
            messages = [{"role": "system", "content": context}, ...]
        """
        latest = CONTEXT_DIR / "latest.txt"
        if latest.exists():
            return latest.read_text()
        # Fallback: generate on the fly
        result = self.run_daily_publish()
        if latest.exists():
            return latest.read_text()
        return f"[Epistemic Commons not yet generated for {self.today}]"

    def get_todays_commons(self) -> dict:
        """Returns today's commons packet as a dict."""
        path = DAILY_DIR / f"{self.today}.json"
        if path.exists():
            try:
                return json.loads(path.read_text())
            except Exception:
                pass
        return {}

    def get_commons_stats(self, days: int = 30) -> dict:
        """Return aggregate stats for the last N days."""
        count      = 0
        total_seeds = 0
        total_steelmans = 0
        cutoff = (datetime.date.today() - datetime.timedelta(days=days)).isoformat()

        for f in DAILY_DIR.glob("*.json"):
            if f.stem >= cutoff:
                try:
                    d = json.loads(f.read_text())
                    total_seeds     += d.get("metrics", {}).get("seeds_count", 0)
                    total_steelmans += d.get("metrics", {}).get("steelmans_count", 0)
                    count += 1
                except Exception:
                    pass

        steelman_count = 0
        if STEELMAN_ARCHIVE.exists():
            steelman_count = sum(1 for _ in STEELMAN_ARCHIVE.read_text().strip().split("\n") if _)

        return {
            "days_published":     count,
            "total_seeds":        total_seeds,
            "total_steelmans":    total_steelmans,
            "archive_steelmans":  steelman_count,
            "commons_url":        f"{COMMONS_SOURCE}/tree/main/epistemic_commons",
            "ai_context_url":     f"{COMMONS_SOURCE}/blob/main/epistemic_commons/ai_context/latest.txt",
        }

    # ══════════════════════════════════════════════════════════════════════════
    # HELPERS
    # ══════════════════════════════════════════════════════════════════════════

    def _load_swarm_status(self) -> dict:
        if SWARM_STATUS.exists():
            try:
                return json.loads(SWARM_STATUS.read_text())
            except Exception:
                pass
        return {"wonder_index": 1.0, "inter_rune_coherence": 1.0, "mets": 0}

    def _call_ollama(self, prompt: str) -> str:
        try:
            r = requests.post(
                OLLAMA_URL,
                json={"model": OLLAMA_MODEL,
                      "messages": [{"role": "user", "content": prompt}],
                      "stream": False, "temperature": 0.75},
                timeout=OLLAMA_TIMEOUT,
            )
            if r.status_code == 200:
                return r.json()["choices"][0]["message"]["content"].strip()
        except Exception as e:
            print(f"[commons] Ollama error: {e}")
        return ""


